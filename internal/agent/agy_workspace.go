// The Antigravity CLI (agy) has no per-invocation flag for MCP servers or
// for the system prompt. It reads both from the workspace — the process
// cwd, which for a kojo turn is the agent directory:
//
//   - <dir>/.agents/mcp_config.json  MCP servers ({"mcpServers": {...}})
//   - <dir>/.agents/rules/kojo-system-NN.md  always_on prompt rules. agy
//     reads them again before every model step (not only at start-up), so
//     they carry kojo's shared system prompt (persona, memory, ...), which
//     changes between the turns of one conversation.
//   - <dir>/.agents/agents/<name>/agent.md  a custom agent, selected with
//     --agent <name>. It sets the tool policy and carries the per-call
//     SystemPromptExtra (thread / Slack context). agy freezes its body
//     when a conversation is created (see agyResumeExtraNotice).
//
// kojo owns these files and rewrites them before every turn. One agent can
// run several agy turns at once (its own chat plus thread / external
// sessions). Every distinct custom agent body gets its own agent,
// kojo-<hash of the body>, so turns with different extras never wait on
// each other for it. mcp_config.json has a fixed path shared by every turn
// of the agent; a turn that needs it to say something else waits until the
// turns started against the current content have exited (the same scheme
// as holdGrokMCPConfig). The rules are shared too but never waited for:
// every turn of an agent builds the same shared prompt (prepareChat keeps
// per-surface differences in the extra for agy), so two turns' rules
// differ only when the agent's persona / memory files changed in between.
// The newest write wins; a running turn, which re-reads the rules every
// step, just picks up the fresher prompt. Waiting instead would hold a
// thread turn until a main-chat turn that edited MEMORY.md had exited.

const (
	// agyKojoAgentPrefix starts the name of every custom agent kojo
	// generates; agyAgentName appends the body hash.
	agyKojoAgentPrefix = "kojo-"
	// agyMCPTimeoutSeconds lifts agy's per-call MCP limit (3 minutes):
	// kojo's own MCP tools (exec, long searches) can run far longer, and
	// the turn timeout already bounds the run.
	agyMCPTimeoutSeconds = 3600
)

func agyMCPConfigPath(agentDirPath string) string {
	return filepath.Join(agentDirPath, ".agents", "mcp_config.json")
}

func agyAgentsDir(agentDirPath string) string {
	return filepath.Join(agentDirPath, ".agents", "agents")
}

// agyAgentName names the custom agent whose body (agyAgentDefBody) is
// body. agy looks a custom agent up by the name in its frontmatter; the
// directory is named the same.
func agyAgentName(body string) string {
	sum := sha256.Sum256([]byte(body))
	return agyKojoAgentPrefix + hex.EncodeToString(sum[:8])
}

// agyGeneratedAgentDescription marks the agent defs kojo generates; the
// sweep removes nothing without it.
const agyGeneratedAgentDescription = "kojo agent (generated by kojo for every turn; edits are lost)"

// agyGeneratedAgentDir matches the directories of the custom agents kojo
// generates, plus "kojo", the single shared one of earlier versions.
var agyGeneratedAgentDir = regexp.MustCompile(`^kojo(-[0-9a-f]{16})?$`)

func agyAgentDefPath(agentDirPath, name string) string {
	return filepath.Join(agyAgentsDir(agentDirPath), name, "agent.md")
}

// agyWorkspaceMu guards the managed files and agyWorkspaceHolds.
var agyWorkspaceMu sync.Mutex

type agyWorkspaceHold struct {
	content string
	users   int
	freed   chan struct{} // closed when users drops to zero
}

// agyWorkspaceHolds maps a managed file path to the content the running
// turns were started against.
var agyWorkspaceHolds = map[string]*agyWorkspaceHold{}

// agyPromptGeneration numbers system prompts in the order they were
// built (prepareChat draws one just before reading the persona / memory
// files). agyRulesWritten records, per agent directory, the generation of
// the rules on disk, so a turn that reaches holdAgyWorkspace late (slow
// effort resolution, waiting for mcp_config.json) never puts an older
// prompt back over a newer turn's. agyRulesWritten is guarded by
// agyWorkspaceMu.
var (
	agyPromptGeneration atomic.Uint64
	agyRulesWritten     = map[string]uint64{}
)

func nextAgyPromptGeneration() uint64 { return agyPromptGeneration.Add(1) }

// renderAgyMCPConfig renders mcp_config.json, or "" when there is nothing
// to declare (the file is then removed).
func renderAgyMCPConfig(servers map[string]mcpServerEntry) (string, error) {
	type entry struct {
		Command        string            `json:"command,omitempty"`
		Args           *[]string         `json:"args,omitempty"`
		Env            map[string]string `json:"env,omitempty"`
		ServerURL      string            `json:"serverUrl,omitempty"`
		Headers        map[string]string `json:"headers,omitempty"`
		TimeoutSeconds int               `json:"timeoutSeconds"`
	}
	out := map[string]entry{}
	for name, e := range servers {
		if name == "" || (e.Command == "" && e.URL == "") {
			continue
		}
		if e.isStdio() {
			args := e.Args
			if args == nil {
				args = []string{}
			}
			out[name] = entry{Command: e.Command, Args: &args, Env: e.Env, TimeoutSeconds: agyMCPTimeoutSeconds}
		} else {
			out[name] = entry{ServerURL: e.URL, Headers: e.Headers, TimeoutSeconds: agyMCPTimeoutSeconds}
		}
	}
	if len(out) == 0 {
		return "", nil
	}
	b, err := json.MarshalIndent(map[string]any{"mcpServers": out}, "", "  ")
	if err != nil {
		return "", err
	}
	return string(b) + "\n", nil
}

// agyAgentTools is the tool set of the kojo custom agent. A custom agent
// gets only the tools its frontmatter lists (none without the key), and
// names agy does not know fail the whole run, so this is the default
// agent's tool set minus the names agy 1.4.8 refuses there (browser_*,
// command_status, ...) and minus schedule / search_marketplace, which
// kojo does not want agents to use. MCP servers from mcp_config.json are
// reachable regardless (call_mcp_tool is added by agy).
var agyAgentTools = []string{
	"ask_custom_permission", "ask_permission", "ask_question", "define_subagent",
	"find_by_name", "finish", "generate_image", "grep_search", "invoke_subagent",
	"list_dir", "list_plugin_accounts", "manage_subagents", "manage_task",
	"multi_replace_file_content", "notebook_edit", "read_url_content",
	"replace_file_content", "run_command", "run_workflow", "search_web",
	"send_message", "view_file", "wait", "write_to_file",
}

// agyRulesPointer opens every generated agent body. The body is frozen
// with the conversation, so it only points at the rules, which carry the
// current shared prompt on every turn.
const agyRulesPointer = "Follow the current kojo instructions in .agents/rules/kojo-system-*.md. " +
	"Those rules are refreshed every turn; the latest version replaces earlier kojo rule snapshots in the conversation.\n"

// agyAgentDefBody is the body of the custom agent for a turn whose
// per-call SystemPromptExtra is extra.
func agyAgentDefBody(extra string) string {
	if extra == "" {
		return agyRulesPointer
	}
	return agyRulesPointer + "\n" + extra + "\n"
}

// renderAgyAgentDef renders the custom agent name with body: kojo's tool
// policy, then the body.
func renderAgyAgentDef(name, body string) string {
	return "---\nname: " + name +
		"\ndescription: " + agyGeneratedAgentDescription +
		"\ntools: [" + strings.Join(agyAgentTools, ", ") + "]" +
		"\n---\n" + body
}

// holdAgyWorkspace makes the managed files say exactly files (path →
// content; "" removes the file) and keeps them that way until release is
// called, which the caller does once its agy process has exited. A file
// held with other content is waited for; files listed in ephemeral are
// removed again once their last holder released them. kojo rule chunks
// are written (and stale ones pruned) without a hold: the newest turn's
// rules win (see the package comment above).
//
// gen is the generation of the prompt the rules in files carry (0: draw
// one now).
func holdAgyWorkspace(ctx context.Context, agentDirPath string, gen uint64, files map[string]string, ephemeral ...string) (release func(), err error) {
	if gen == 0 {
		gen = nextAgyPromptGeneration()
	}
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for {
		agyWorkspaceMu.Lock()
		if conflict := agyWorkspaceConflictLocked(agentDirPath, files); conflict != nil {
			agyWorkspaceMu.Unlock()
			select {
			case <-conflict:
				continue
			case <-ctx.Done():
				return nil, ctx.Err()
			}
		}
		// A newer turn's rules are already on disk: leave them (and their
		// chunk set) alone and run on them.
		writeRules := agyRulesWritten[agentDirPath] < gen
		if writeRules {
			agyRulesWritten[agentDirPath] = gen
		}
		// Also under a hold of the same content: the files may have been
		// edited since, and putting back what the running turns were
		// started with takes nothing from them.
		if err := prepareAgyManagedPaths(agentDirPath, files, writeRules); err != nil {
			agyWorkspaceMu.Unlock()
			return nil, err
		}
		for _, p := range paths {
			if !writeRules && isAgyRuleChunkPath(agentDirPath, p) {
				continue
			}
			if err := syncAgyManagedFile(p, files[p]); err != nil {
				agyWorkspaceMu.Unlock()
				return nil, err
			}
		}
		holds := make(map[string]*agyWorkspaceHold, len(paths))
		for _, p := range paths {
			if isAgyRuleChunkPath(agentDirPath, p) {
				continue
			}
			h := agyWorkspaceHolds[p]
			if h == nil {
				h = &agyWorkspaceHold{content: files[p], freed: make(chan struct{})}
				agyWorkspaceHolds[p] = h
			}
			h.users++
			holds[p] = h
		}
		sweepAgyAgentDefsLocked(agentDirPath)
		agyWorkspaceMu.Unlock()

		var once sync.Once
		return func() {
			once.Do(func() {
				agyWorkspaceMu.Lock()
				defer agyWorkspaceMu.Unlock()
				for p, h := range holds {
					if h.users--; h.users > 0 {
						continue
					}
					delete(agyWorkspaceHolds, p)
					close(h.freed)
					if slices.Contains(ephemeral, p) {
						_ = os.RemoveAll(filepath.Dir(p))
					}
				}
			})
		}, nil
	}
}

// agyWorkspaceConflictLocked returns the hold a turn wanting files must
// wait for, or nil. Caller holds agyWorkspaceMu.
func agyWorkspaceConflictLocked(agentDirPath string, files map[string]string) chan struct{} {
	for p, content := range files {
		if isAgyRuleChunkPath(agentDirPath, p) {
			continue
		}
		if h := agyWorkspaceHolds[p]; h != nil && h.content != content {
			return h.freed
		}
	}
	return nil
}

// isAgyRuleChunkPath reports whether p is one of kojo's numbered rule
// chunks, which holdAgyWorkspace writes without holding them.
func isAgyRuleChunkPath(agentDirPath, p string) bool {
	return filepath.Dir(p) == agyRulesDir(agentDirPath) && isAgyManagedRuleName(filepath.Base(p))
}

// sweepAgyAgentDefsLocked removes the generated custom agents no running
// turn holds: those of a kojo that exited mid-turn, and the shared "kojo"
// one of earlier versions. agy reads its agent def at start-up (a run
// whose def is deleted mid-turn keeps its prompt), so an agy outliving its
// kojo loses nothing. Caller holds agyWorkspaceMu and has checked the
// agents directory with prepareAgyManagedPaths.
func sweepAgyAgentDefsLocked(agentDirPath string) {
	entries, err := os.ReadDir(agyAgentsDir(agentDirPath))
	if err != nil {
		return
	}
	for _, e := range entries {
		if !e.IsDir() || !agyGeneratedAgentDir.MatchString(e.Name()) {
			continue
		}
		def := agyAgentDefPath(agentDirPath, e.Name())
		if agyWorkspaceHolds[def] != nil {
			continue
		}
		if b, err := readAgyStateFile(def); err != nil || !strings.Contains(string(b), "\ndescription: "+agyGeneratedAgentDescription+"\n") {
			continue
		}
		_ = os.RemoveAll(filepath.Join(agyAgentsDir(agentDirPath), e.Name()))
	}
}

// Check every managed parent before writing or removing anything. A
// symlink in the writable workspace must not redirect MCP tokens, rules
// or the agent-def sweep outside the agent directory. With pruneRules,
// kojo's numbered rule files that files does not list are removed; no
// other file is.
func prepareAgyManagedPaths(dir string, files map[string]string, pruneRules bool) error {
	paths := []string{filepath.Join(dir, ".agents"), agyRulesDir(dir), agyAgentsDir(dir)}
	for path := range files {
		rel, err := filepath.Rel(dir, path)
		if err != nil || rel == "." || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) || filepath.IsAbs(rel) {
			return fmt.Errorf("agy managed path outside agent directory: %s", path)
		}
		for parent := filepath.Dir(path); parent != dir; parent = filepath.Dir(parent) {
			paths = append(paths, parent)
		}
	}
	if err := geminiRefuseSymlinks(paths...); err != nil {
		return err
	}
	if !pruneRules {
		return nil
	}
	entries, err := os.ReadDir(agyRulesDir(dir))
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, entry := range entries {
		name := entry.Name()
		if !isAgyManagedRuleName(name) {
			continue
		}
		path := filepath.Join(agyRulesDir(dir), name)
		if _, keep := files[path]; !keep {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}

// syncAgyManagedFile writes content to path (0600: an HTTP MCP entry
// carries the agent's kojo token) unless it already says that, or removes
// path when content is "".
func syncAgyManagedFile(path, content string) error {
	if err := agyRefuseFileSymlink(path); err != nil {
		return err
	}
	if content == "" {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	if cur, err := os.ReadFile(path); err == nil && string(cur) == content {
		// A file someone else created with the same content may be
		// world-readable.
		return os.Chmod(path, 0o600)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".kojo-*.tmp")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		os.Remove(tmpPath)
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmpPath)
		return err
	}
	if err := os.Rename(tmpPath, path); err != nil {
		os.Remove(tmpPath)
		return err
	}
	return nil
}
